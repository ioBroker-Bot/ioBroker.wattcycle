/** A text in all languages with a suffix that is the same in all of them, e.g. `Cell 3` */
export function tWith(key: WordKey, suffix: string): ioBroker.Translated {
    const result: Partial<ioBroker.Translated> = {};
    for (const [lang, text] of Object.entries(WORDS[key])) {
        result[lang as ioBroker.Languages] = `${text}${suffix}`;
    }
    return result as ioBroker.Translated;
}
